// js/ai-classify.js — เรียก OpenRouter ให้ช่วยจัดประเภทการลาจากเหตุผลที่พิมพ์
// (US-09 / สัปดาห์ที่ 8) — เรียกตรงจาก browser เพราะสเปกห้ามเขียนเซิร์ฟเวอร์เอง
// ใช้ ai-config.js และรูปแบบ AbortController timeout เดียวกับ ai-summary.js
// แต่ input/output ต่างกัน: input = เหตุผล + รายชื่อประเภทที่มีจริง,
// output ต้องเป็นชื่อประเภทที่ตรงกับรายชื่อที่ส่งไปเท่านั้น
// ─────────────────────────────────────────────────────────────

import { OPENROUTER_API_KEY, OPENROUTER_MODEL } from "./ai-config.js";

var เวลารอสูงสุด = 15000; // ms — ตาม US-09: เรียกไม่สำเร็จหรือรอเกิน 15 วินาที ต้องไม่ค้าง

// รับเหตุผลการลา (ข้อความ) + รายชื่อประเภทการลาที่มีอยู่จริงในระบบตอนนี้ (array ของ name)
// คืนค่า { สำเร็จ: true, ชื่อประเภท } เมื่อ AI เลือกได้ตรงกับชื่อที่มีอยู่จริงเท่านั้น
// หรือ { สำเร็จ: false, เหตุผล } เมื่อเรียกไม่สำเร็จ / หมดเวลา / AI ตอบไม่ตรงกับชื่อที่มีจริงเลย
export async function จัดประเภทลาด้วยAI(เหตุผลการลา, รายชื่อประเภท) {
  if (!รายชื่อประเภท || รายชื่อประเภท.length === 0) {
    return { สำเร็จ: false, เหตุผล: "ยังไม่มีประเภทการลาในระบบให้เลือก" };
  }

  var input =
    "เหตุผลการลา: " + เหตุผลการลา + "\n" +
    "ประเภทการลาที่มีอยู่จริงในระบบ: " + รายชื่อประเภท.join(", ");

  var ตัวตัดเวลา = new AbortController();
  var หมดเวลาแล้ว = setTimeout(function () { ตัวตัดเวลา.abort(); }, เวลารอสูงสุด);

  var response;
  try {
    response = await fetch("https://openrouter.ai/api/v1/chat/completions", {
      method: "POST",
      signal: ตัวตัดเวลา.signal,
      headers: {
        Authorization: "Bearer " + OPENROUTER_API_KEY,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: OPENROUTER_MODEL,
        messages: [
          {
            role: "user",
            content:
              "จากเหตุผลการลาต่อไปนี้ ให้เลือกประเภทการลาที่ตรงที่สุดจากรายชื่อที่กำหนดให้เท่านั้น " +
              "ตอบกลับด้วยชื่อประเภทตัวเดียวจากรายชื่อ ตัวสะกดต้องตรงกันทุกตัวอักษร " +
              "ห้ามตอบอย่างอื่นเพิ่มเติม ห้ามใส่เครื่องหมายคำพูดหรือคำอธิบายใด ๆ:\n\n" + input,
          },
        ],
      }),
    });
  } catch (err) {
    clearTimeout(หมดเวลาแล้ว);
    if (err.name === "AbortError") {
      return { สำเร็จ: false, เหตุผล: "รอเกิน 15 วินาที ระบบไม่สามารถจัดประเภทให้ได้ตอนนี้" };
    }
    return { สำเร็จ: false, เหตุผล: "เรียก AI ไม่สำเร็จ: " + err.message };
  }
  clearTimeout(หมดเวลาแล้ว);

  if (!response.ok) {
    return { สำเร็จ: false, เหตุผล: "เรียก AI ไม่สำเร็จ (HTTP " + response.status + ")" };
  }

  var data;
  try {
    data = await response.json();
  } catch (err) {
    return { สำเร็จ: false, เหตุผล: "อ่านผลลัพธ์จาก AI ไม่สำเร็จ" };
  }

  var ข้อความ = data.choices && data.choices[0] && data.choices[0].message && data.choices[0].message.content;
  if (!ข้อความ || !ข้อความ.trim()) {
    return { สำเร็จ: false, เหตุผล: "AI ไม่ได้ตอบข้อความกลับมา" };
  }

  // ตัดเครื่องหมายคำพูดที่ AI อาจใส่มาล้อมชื่อประเภทออกก่อนเทียบ
  var คำตอบ = ข้อความ.trim().replace(/^["'“”]+|["'“”]+$/g, "").trim();

  // ผลที่ได้ต้องเป็นประเภทการลาที่มีอยู่จริงในระบบเท่านั้น (เทียบตรงตัว ตัดช่องว่างหัวท้าย)
  var ตรงกับ = รายชื่อประเภท.find(function (ชื่อ) { return ชื่อ.trim() === คำตอบ; });
  if (!ตรงกับ) {
    return { สำเร็จ: false, เหตุผล: "AI จัดประเภทให้ไม่ได้ — ผลลัพธ์ไม่ตรงกับประเภทการลาที่มีอยู่จริงในระบบ" };
  }

  return { สำเร็จ: true, ชื่อประเภท: ตรงกับ };
}
